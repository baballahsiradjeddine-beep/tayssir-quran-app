$division = Division::find($divisionId);
$chapterLevelId = App\Models\ChapterLevel::first()->id;

foreach ($levels as $mIdx => $materialData) {
    $colors = [
        ['color' => '#F59E0B', 'secondary' => '#FEF3C7'],
        ['color' => '#D97706', 'secondary' => '#FFEDD5'],
        ['color' => '#B45309', 'secondary' => '#FFF7ED'],
    ];

    $material = Material::create([
        'name' => $materialData['title'],
        'description' => $materialData['description'],
        'code' => 'WARSH_L' . ($mIdx + 1),
        'color' => $colors[$mIdx]['color'],
        'secondary_color' => $colors[$mIdx]['secondary'],
        'active' => true,
    ]);
    
    $division->materials()->attach($material->id, ['sort' => $mIdx + 1]);

    foreach ($materialData['units'] as $uIdx => $unitData) {
        $unit = Unit::create([
            'name' => $unitData['title'],
            'description' => $unitData['description'],
            'active' => true,
        ]);
        
        $material->units()->attach($unit->id, ['sort' => $uIdx + 1]);

        $chapterSort = 1;
        foreach ($unitData['sections'] as $section) {
            foreach ($section['items'] as $item) {
                // Determine type
                $type = in_array($item['type'], ['exercise', 'detect', 'exam']) ? 'exercise' : 'lesson';
                
                $content = null;
                if ($type === 'lesson') {
                    if (in_array($item['type'], ['intro', 'lesson'])) {
                        $content = [
                            [
                                'elements' => [
                                    [
                                        'type' => 'text',
                                        'data' => [
                                            'content' => '<p style="text-align: center;">سيضاف فيديو الشرح قريباً إن شاء الله 📖</p>'
                                        ]
                                    ]
                                ]
                            ]
                        ];
                    } elseif (in_array($item['type'], ['audio', 'warsh'])) {
                        $content = [
                            [
                                'elements' => [
                                    [
                                        'type' => 'flashcards',
                                        'data' => [
                                            'cards' => [
                                                ['front' => 'سيتم إضافة البطاقات التعليمية قريباً', 'back' => 'ترقبوا التحديث القادم!']
                                            ]
                                        ]
                                    ]
                                ]
                            ]
                        ];
                    }
                }

                Chapter::create([
                    'name' => $item['text'],
                    'description' => $section['label'],
                    'type' => $type,
                    'content' => $content,
                    'chapter_level_id' => $chapterLevelId,
                    'active' => true,
                ])->unit()->attach($unit->id, ['sort' => $chapterSort++]);
            }
        }
    }
}

